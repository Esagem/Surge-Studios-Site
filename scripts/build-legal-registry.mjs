// Regenerates src/content/legal/index.ts by scanning the per-app *.json files
// in that folder (each produced by Daedalus/tools/legal_gen). Adding a project
// is then: drop its <slug>.json here and run `node scripts/build-legal-registry.mjs`.
// The app's /<slug>/privacy + /<slug>/terms pages and the master policy's
// "products we cover" list update automatically.
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "content", "legal");
const slugs = readdirSync(dir)
  .filter((f) => f.endsWith(".json"))
  .map((f) => f.replace(/\.json$/, ""))
  .sort();

const imports = slugs.map((s) => `import ${s} from "./${s}.json";`).join("\n");
const entries = slugs.map((s) => `  ${s}: ${s} as AppLegal,`).join("\n");

const out = `// GENERATED by scripts/build-legal-registry.mjs - do not edit by hand.
// Per-app legal content, produced from each app's surge.manifest.yaml by
// Daedalus/tools/legal_gen. The [slug] routes render these via the shared
// LegalShell; the master policy lists them as covered products.
${imports}

export type LegalSection = { heading: string; body: string[] };
export type LegalDoc = {
  title: string;
  eyebrow: string;
  intro: string;
  sections: LegalSection[];
};
export type AppLegal = {
  slug: string;
  appName: string;
  privacy: LegalDoc;
  terms: LegalDoc;
};

const registry: Record<string, AppLegal> = {
${entries}
};

export function getAppLegal(slug: string): AppLegal | undefined {
  return registry[slug];
}

export function legalSlugs(): string[] {
  return Object.keys(registry);
}

// Every app under the Surge Studios LLC umbrella, for the master policy's
// "products we cover" list.
export function coveredApps(): { slug: string; name: string }[] {
  return Object.values(registry)
    .map((a) => ({ slug: a.slug, name: a.appName }))
    .sort((a, b) => a.name.localeCompare(b.name));
}
`;

writeFileSync(join(dir, "index.ts"), out);
console.log(`Wrote src/content/legal/index.ts (${slugs.length} apps: ${slugs.join(", ")}).`);
